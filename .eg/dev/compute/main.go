// Package main runs an eg daemon from the checked out source, registered using an identity seed and talking to the egmeta
// development services on the container host.
// usage: eg compute serve --ttl infinity dev/compute
package main

import (
	"context"
	"log"

	"github.com/egdaemon/eg/runtime/wasi/eg"
	"github.com/egdaemon/eg/runtime/wasi/egenv"
	"github.com/egdaemon/eg/runtime/wasi/eggit"
	"github.com/egdaemon/eg/runtime/wasi/shell"
	"github.com/egdaemon/eg/runtime/x/wasi/eggolang"
)

// daemon runs the daemon and, when anything fails, keeps the workload alive until the ttl instead of closing it
// so the environment can be inspected and the steps reproduced by hand. the failure is logged and returned afterwards.
func daemon(ctx context.Context, op eg.Op) error {
	err := run(ctx, op)
	if err == nil {
		return nil
	}

	log.Println("daemon failed, keeping the workload alive for debugging:", err)
	if cause := shell.Run(ctx, shell.New("tail -f /dev/null").Timeout(egenv.TTL()).Lenient(true)); cause != nil {
		log.Println("unable to keep the workload alive:", cause)
	}

	return err
}

func run(ctx context.Context, _ eg.Op) error {
	// the default hosts are compile time variables, the shell expands them from the environment.
	// the defaults point at the egmeta development services on the container host, see egmeta/.eg/dev/daemon.
	// tls is insecure because the development services use an autogenerated certificate.
	envfile := egenv.DirectoryWorkload("compute.env")
	runtime := shell.Runtime().
		EnvironFrom(eggolang.Env()...).
		Environ("CACHE_DIRECTORY", egenv.DirectoryCache()).
		Environ("EG_ACCOUNT", egenv.String("00000000-0000-0000-0000-000000000001", "EG_ACCOUNT")).
		// the seed of the daemon identity, egmeta's dev/daemon preauthorizes the identity derived from it. it must not
		// be exported as EG_SSH_KEY_SEED: that takes precedence over the derived EG_ENTROPY_SEED the daemon is meant to use.
		Environ("EG_DEV_SEED", egenv.String("00000000-0000-0000-0000-000000000002", "EG_DEV_SEED", "EG_SSH_KEY_SEED")).
		// the workload environment sets this from the launching eg, which overrides the compiled default.
		Environ("EG_COMPUTE_TLS_INSECURE", "true").
		Environ("EG_DEV_API_HOST", egenv.String("https://host.containers.internal:8081", "EG_DEV_API_HOST")).
		Environ("EG_DEV_CONSOLE_HOST", egenv.String("https://host.containers.internal:8080", "EG_DEV_CONSOLE_HOST"))

	// the eg on the PATH points at the production hosts, so the freshly installed binary is always invoked by path.
	err := shell.Run(
		ctx,
		runtime.New(`go install -ldflags="-X github.com/egdaemon/eg.apiHostDefault=${EG_DEV_API_HOST} -X github.com/egdaemon/eg.consoleHostDefault=${EG_DEV_CONSOLE_HOST} -X github.com/egdaemon/eg.containerAPIHostDefault=${EG_DEV_API_HOST} -X github.com/egdaemon/eg.tlsinsecure=true" ./cmd/eg`),
		// the daemon is preauthorized by egmeta's dev/daemon (egci-meta accounts create), no authorize step is needed.
		// bootstrap env derives the daemon's seed the same way authorize would, and the daemon consumes the derived value.
		runtime.Newf("~/go/bin/eg actl bootstrap env daemon --account=${EG_ACCOUNT} --seed=${EG_DEV_SEED} -e EG_COMPUTE_TLS_INSECURE=true | tee %s", envfile),
	)
	if err != nil {
		return err
	}

	// the daemon builds containers, nested inside this one that needs the user's systemd session to create scopes.
	// so it runs there like egmeta's dev/daemon does, the session loads the daemon's environment from the file.
	// the session's own environment is used, so an EG_SSH_KEY_SEED exported by the launching shell can't take
	// precedence over the derived EG_ENTROPY_SEED the daemon must use.
	return shell.Run(
		ctx,
		// diagnostics, exec status 203 is also what systemd reports when it can't load an EnvironmentFile. each probe adds
		// one piece of the real command: a plain binary, then the env file, then the eg binary itself.
		shell.New("machinectl shell egd@.host /usr/bin/systemd-run --user --pty --wait /usr/bin/id").Privileged().Lenient(true),
		shell.Newf("machinectl shell egd@.host /usr/bin/systemd-run --user --pty --wait --property=EnvironmentFile=%s /usr/bin/id", envfile).Privileged().Lenient(true),
		shell.New("machinectl shell egd@.host /usr/bin/systemd-run --user --pty --wait /home/egd/go/bin/eg version").Privileged().Lenient(true),
		shell.New(
			"machinectl shell egd@.host /usr/bin/systemd-run --user --pty --wait --property=EnvironmentFile=${COMPUTE_ENV} ~/go/bin/eg daemon",
		).Environ("COMPUTE_ENV", envfile).Privileged().Timeout(egenv.TTL()),
	)
}

func main() {
	log.SetFlags(log.Lshortfile | log.LUTC | log.Ltime)
	ctx, done := context.WithTimeout(context.Background(), egenv.TTL())
	defer done()

	c1 := eg.Container("eg.ubuntu")
	err := eg.Perform(
		ctx,
		eggit.AutoClone,
		eg.Build(
			c1.BuildFromFile(".eg/Containerfile"),
		),
		eg.Module(
			ctx,
			c1,
			daemon,
		),
	)

	if err != nil {
		log.Fatalln(err)
	}
}
