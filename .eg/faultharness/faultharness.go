// Package faultharness generates a test case reproducing each fault of a source of faults, e.g.) the errors
// reported to an error tracker, and pushes them to a branch per fault. it is the testgen harness with
// faults as the source of the functions instead of the least covered functions.
package faultharness

import (
	"github.com/egdaemon/eg/runtime/wasi/eg"
	"github.com/egdaemon/eg/runtime/wasi/eggit"
	"github.com/egdaemon/eg/runtime/wasi/shell"
	"github.com/egdaemon/eg/runtime/x/wasi/egautogen"
	"github.com/egdaemon/eg/runtime/x/wasi/egbug"
	"github.com/egdaemon/eg/runtime/x/wasi/egpool"
)

// T is an error reported by a source, reduced to what is needed to reproduce it.
type T struct {
	ID         string
	Stacktrace string
	// Path, Func, and Line are the top frame of the stacktrace that is in this repository.
	Path string
	Func string
	Line int
}

// Seq is a source of faults. sources implement it, it is evaluated when the harness runs.
type Seq = egpool.Seq[T]

// Test generates a test case reproducing each fault of seq as configured by opts, e.g.) the judge
// and the number of attempts, running at most workers at once, each in its own worktree so they
// never write the same file.
func Test(workers uint16, opts egautogen.Options, seq Seq) eg.OpFn {
	return pool(workers, opts).Run(seq)
}

// pool is the pool generating the test cases of the faults it is given.
func pool(workers uint16, opts egautogen.Options) egpool.Pool[T] {
	opts = opts.Ensure(
		"no helper functions are added",
		"no global variables or setup code",
		"you must not change non-test code",
		"the test reproduces the reported error",
	)

	return egpool.New(workers, func(f T) eg.OpFn {
		return eggit.Change("egfault:" + f.ID).Op(func(c eggit.Changer) eg.OpFn {
			return test(c, f, opts.Run(generator{fault: f, dir: c.Path()}))
		})
	})
}

// test runs the op generating the test case of a fault and pushes it to its own branch.
func test(c eggit.Changer, f T, generate eg.OpFn) eg.OpFn {
	return eg.Sequential(
		generate,
		egbug.Log("faultharness completed "+f.ID),
		shell.Op(c.Runtime().New("git diff .")),
		egbug.Log("submitting branch initiated "+f.ID),
		eggit.Commit(
			c,
			eggit.NewCommit("test: reproduce fault "+f.ID+"\n\nGenerated by dev/egautogen.").
				Branch(eggit.Pattern("egfault/tests-%git.hash.short%-"+f.ID)),
		),
		eggit.Push(c),
		egbug.Log("submitting branch completed "+f.ID),
	)
}
