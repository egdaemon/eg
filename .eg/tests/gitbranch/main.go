// Package gitbranch provides tests for eggit.SubmitBranch on the host and within a container.
// when cloning is disabled (eg compute local) it verifies the patch written to the cache directory,
// otherwise it verifies the branch was pushed to the remote and then removes it.
package main

import (
	"context"
	"encoding/base64"
	"errors"
	"log"
	"strings"

	"github.com/egdaemon/eg"
	wasieg "github.com/egdaemon/eg/runtime/wasi/eg"
	"github.com/egdaemon/eg/runtime/wasi/egenv"
	"github.com/egdaemon/eg/runtime/wasi/eggit"
	"github.com/egdaemon/eg/runtime/wasi/egunsafe/ffigit"
	"github.com/egdaemon/eg/runtime/wasi/env"
	"github.com/egdaemon/eg/runtime/wasi/shell"
	"github.com/egdaemon/eg/runtime/x/wasi/egbug"
)

// branch names are unique per environment and per commit so concurrent runs do not collide.
func branchname(environment string) string {
	return eggit.StringReplace("egtest/gitbranch-" + environment + "-%git.hash.short%-%git.commit.unix%")
}

// git command authenticated the same way SubmitBranch authenticates its push.
func authed() shell.Command {
	cmd := shell.Runtime()
	token := ffigit.Bearer()
	if strings.TrimSpace(token) == "" {
		return cmd
	}

	creds := base64.StdEncoding.EncodeToString([]byte("x-access-token:" + token))
	return cmd.
		Environ("GIT_CONFIG_COUNT", 1).
		Environ("GIT_CONFIG_KEY_0", "http.extraheader").
		Environ("GIT_CONFIG_VALUE_0", "Authorization: Basic "+creds)
}

// script setting $target to the https form of the remote, mirrors what SubmitBranch pushes to.
func target(remote string) string {
	return strings.Join([]string{
		"target=$(git remote get-url " + remote + ")",
		`case "$target" in`,
		`http://*|https://*) ;;`,
		`ssh://*@*) target="https://${target#ssh://*@}" ;;`,
		`*@*:*) rest="${target#*@}"; target="https://${rest%%:*}/${rest#*:}" ;;`,
		`esac`,
	}, "\n")
}

// dirty ensures the workspace has changes, SubmitBranch does nothing for a clean workspace.
func dirty(environment string) wasieg.OpFn {
	return func(ctx context.Context, _ wasieg.Op) error {
		return shell.Run(ctx, shell.Newf("echo %s > .eg-gitbranch-%s", environment, environment))
	}
}

// verify the outcome of SubmitBranch for the current mode.
func verify(environment string) wasieg.OpFn {
	return func(ctx context.Context, _ wasieg.Op) error {
		branch := branchname(environment)

		if !env.Boolean(true, eg.EnvUnsafeGitCloneEnabled) {
			patch := egenv.CacheDirectory("egpatches", strings.ReplaceAll(branch, "/", "-")+".patch")
			return shell.Run(ctx, shell.Newf("test -s %s", patch))
		}

		remote := env.String("origin", "EG_GIT_HEAD_REMOTE")
		git := authed()

		found := shell.Run(ctx, git.Newf("%s\ngit ls-remote --exit-code --heads \"$target\" %s", target(remote), branch))
		// always attempt cleanup so failed runs do not leave branches behind.
		removed := shell.Run(ctx, git.Newf("%s\ngit push \"$target\" --delete %s", target(remote), branch))

		return errors.Join(found, removed)
	}
}

func submit(environment string) wasieg.OpFn {
	return wasieg.Sequential(
		egbug.Log("gitbranch", environment, "initiated"),
		dirty(environment),
		eggit.SubmitBranch(
			branchname(environment),
			"test: gitbranch workload\n\nGenerated by tests/gitbranch.",
		),
		verify(environment),
		egbug.Log("gitbranch", environment, "successful"),
	)
}

func main() {
	log.SetFlags(log.Lshortfile | log.LUTC | log.Ltime)
	ctx, done := context.WithTimeout(context.Background(), egenv.TTL())
	defer done()

	c1 := wasieg.Container("eg.ubuntu")
	err := wasieg.Perform(
		ctx,
		eggit.AutoClone,
		wasieg.Build(wasieg.DefaultModule()),
		wasieg.Build(c1.BuildFromFile(".eg/Containerfile")),
		wasieg.Module(ctx, wasieg.DefaultModule(), submit("host")),
		wasieg.Module(ctx, c1, submit("container")),
	)

	if err != nil {
		log.Fatalln(err)
	}
}
