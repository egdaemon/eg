// Package gitbranch provides tests for eggit.Change, Commit and Push on the host and within a container.
// when cloning is disabled (eg compute local) it verifies the patch written to the cache directory,
// otherwise it verifies the branch was pushed to the remote and then removes it.
package main

import (
	"context"
	"encoding/base64"
	"errors"
	"log"
	"strings"

	_eg "github.com/egdaemon/eg"
	"github.com/egdaemon/eg/runtime/wasi/eg"
	"github.com/egdaemon/eg/runtime/wasi/egenv"
	"github.com/egdaemon/eg/runtime/wasi/eggit"
	"github.com/egdaemon/eg/runtime/wasi/egunsafe/ffigit"
	"github.com/egdaemon/eg/runtime/wasi/env"
	"github.com/egdaemon/eg/runtime/wasi/shell"
	"github.com/egdaemon/eg/runtime/x/wasi/egbug"
)

// branch names are unique per run so runs of the same commit do not collide.
func branchname() string {
	return eggit.StringReplace("egtest/gitbranch-%git.hash.short%-" + env.String("local", _eg.EnvComputeRunID))
}

// git command authenticated the same way Push authenticates its push.
func authed() shell.Command {
	cmd := shell.Runtime()
	token := ffigit.Bearer()
	if strings.TrimSpace(token) == "" {
		return cmd
	}

	creds := base64.StdEncoding.EncodeToString([]byte("x-access-token:" + token))
	return cmd.
		Environ("GIT_CONFIG_COUNT", 1).
		Environ("GIT_CONFIG_KEY_0", "http.extraheader").
		Environ("GIT_CONFIG_VALUE_0", "Authorization: Basic "+creds)
}

// script setting $target to the https form of the remote, mirrors what Push pushes to.
func target(remote string) string {
	return strings.Join([]string{
		"target=$(git remote get-url " + remote + ")",
		`case "$target" in`,
		`http://*|https://*) ;;`,
		`ssh://*@*) target="https://${target#ssh://*@}" ;;`,
		`*@*:*) rest="${target#*@}"; target="https://${rest%%:*}/${rest#*:}" ;;`,
		`esac`,
	}, "\n")
}

// dirty ensures the change has modifications, Commit does nothing for a clean change.
func dirty(c eggit.Changer) eg.OpFn {
	return func(ctx context.Context, _ eg.Op) error {
		return shell.Run(ctx, c.Runtime().New("echo gitbranch > .eg-gitbranch"))
	}
}

// verify the outcome of Push for the current mode.
func verify(ctx context.Context, _ eg.Op) error {
	branch := branchname()

	if !env.Boolean(true, _eg.EnvUnsafeGitCloneEnabled) {
		patch := egenv.CacheDirectory("egpatches", strings.ReplaceAll(branch, "/", "-")+".patch")
		return shell.Run(ctx, shell.Newf("test -s %s", patch))
	}

	remote := env.String("origin", "EG_GIT_HEAD_REMOTE")
	git := authed()

	found := shell.Run(ctx, git.Newf("%s\ngit ls-remote --exit-code --heads \"$target\" %s", target(remote), branch))
	// always attempt cleanup so failed runs do not leave branches behind.
	removed := shell.Run(ctx, git.Newf("%s\ngit push \"$target\" --delete %s", target(remote), branch))

	return errors.Join(found, removed)
}

func submit() eg.OpFn {
	change := eggit.Change(egenv.EphemeralDirectory("gitbranch", env.String("local", _eg.EnvComputeRunID)))

	return eg.Sequential(
		egbug.Log("gitbranch initiated"),
		change.Op(dirty),
		eggit.Commit(change, eggit.NewCommit("test: gitbranch workload\n\nGenerated by tests/gitbranch.").Branch(branchname())),
		eggit.Push(change),
		verify,
		egbug.Log("gitbranch successful"),
	)
}

func main() {
	log.SetFlags(log.Lshortfile | log.LUTC | log.Ltime)
	ctx, done := context.WithTimeout(context.Background(), egenv.TTL())
	defer done()

	c1 := eg.Container("eg.ubuntu")
	err := eg.Perform(
		ctx,
		eggit.AutoClone,
		eg.Build(eg.DefaultModule()),
		eg.Build(c1.BuildFromFile(".eg/Containerfile")),
		eg.Module(ctx, eg.DefaultModule(), submit()),
		eg.Module(ctx, c1, submit()),
	)

	if err != nil {
		log.Fatalln(err)
	}
}
