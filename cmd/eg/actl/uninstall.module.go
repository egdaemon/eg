package actl

import (
	"os"
	"path/filepath"

	"github.com/egdaemon/eg/cmd/cmdopts"
	"github.com/egdaemon/eg/compile"
	"github.com/egdaemon/eg/internal/errorsx"
)

type UninstallModule struct {
	Dir      string `name:"directory" help:"root directory to use" default:"${vars_git_directory}"`
	Relative string `name:"relative" help:"relative path from the directory the module lives within" default:"${vars_workload_directory}"`
	Force    bool   `name:"force" help:"remove the module even when it contains files that were not generated by bootstrap"`
}

func (t UninstallModule) Run(gctx *cmdopts.Global) (err error) {
	egdir := filepath.Join(t.Dir, t.Relative)
	entries, err := os.ReadDir(egdir)
	if os.IsNotExist(err) {
		return errorsx.UserFriendly(errorsx.Errorf("no eg module found: %s", egdir))
	} else if err != nil {
		return errorsx.Wrapf(err, "unable to read module directory: %s", egdir)
	}

	// the files `bootstrap module` generates, anything else is the user's.
	generated := map[string]bool{".gitignore": true, "go.mod": true, "go.sum": true, "main.go": true}
	for _, entry := range entries {
		if !t.Force && !generated[entry.Name()] {
			return errorsx.UserFriendly(errorsx.Errorf("refusing to remove a module containing files that were not generated by bootstrap, use --force to remove it anyway: %s", filepath.Join(egdir, entry.Name())))
		}
	}

	if err = compile.DropWorkspaceModule(gctx.Context, egdir); err != nil {
		return err
	}

	return errorsx.Wrapf(os.RemoveAll(egdir), "unable to remove module directory: %s", egdir)
}
