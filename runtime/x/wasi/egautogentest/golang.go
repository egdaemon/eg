var golangPromptTemplate = template.Must(template.New("golang").Parse(`
test the following codeblock using the given coding style and example usage blocks as guidance for how to structure the code.
rules:
{{range .Ensure}}- {{.}}
{{end}}
--------------------------------------------------- STYLE EXAMPLES ---------------------------------------------------
{{.Style}}
--------------------------------------------------- USAGE EXAMPLES ---------------------------------------------------
{{.Usage}}
---------------------------------------------------     TYPES      ---------------------------------------------------
{{.Types}}
---------------------------------------------------    PACKAGE     ---------------------------------------------------
{{if .External}}the code block is exported from package {{.Package}}, so test it as an external caller: your file must declare "package {{.TestPackage}}", import the package under test as "{{.ImportPath}}" and qualify its identifiers with "{{.Package}}."
{{else}}the code block is in package {{.Package}} and is not part of its public api, so your file must declare "package {{.TestPackage}}" and use it directly.
{{end}}{{if .Imports}}the file containing it imports:
{{.Imports}}
{{end}}{{if .Existing}}---------------------------------------------------  EXISTING TESTS ---------------------------------------------------
the test file {{.ExistingFile}} already exists, your response replaces it so it must keep its package clause and contain all of its existing tests along with the new ones.
{{.Existing}}
{{end}}---------------------------------------------------   CODE BLOCK   ---------------------------------------------------
{{.Codeblock}}
---------------------------------------------------     FOCUS      ---------------------------------------------------
{{.Fn.Name}}
`))

// golangDefaultRules are the rules always applied, rules given by the caller are added to them.
var golangDefaultRules = []string{
	"you must respond with only a single complete go test file, including its package clause and imports, as plain text without code fences or any other text.",
	"immediately after the imports statements seperated by a newline there must be exactly this comment, followed by a blank line before the package clause: // DO NOT EDIT: This file was auto generated by egautotest.",
	"other than that first line comment you must not include *any* comments",
	"you must not share variables between tests.",
	"you must not use or create mocking/stub or any kind of code that acts as a substitute that you do not find in samples.",
	"you must not do not write commented out code.",
	"you must not do not document the tests.",
	"you must omit the test if you can't write an effective test.",
	"you must ensure the test cases are comprehensive.",
}

// golangPrompt is the data the golang prompt template is executed with.
type golangPrompt struct {
	PromptContext
	Style        string
	Usage        string
	Types        string
	Package      string // package name of the code block.
	TestPackage  string // package name the generated test file must declare.
	ImportPath   string // import path of the package, for external tests.
	External     bool   // the test is in the external package (Package_test), used for public apis.
	Imports      string // import declarations of the file containing the code block.
	Codeblock    string
	Existing     string // contents of the test file being generated, if it already exists.
	ExistingFile string // name of the test file being generated.
}

// golangOption is the resolved configuration of the Golang generator.
type golangOption struct {
	seq      iterx.Seq[Fn]
	style    string
	filename string
	packages []string
	pkgs     *pkgcache
	callers  *callcache
}

// DefaultGolangFilename is the pattern for the name of the file generated tests are written to.
const DefaultGolangFilename = "%fn.file%.%fn.name%.autogentest_test.go"

// GolangOption configures the Golang generator.
type GolangOption func(*golangOption)

// GolangOptions is a chainable set of GolangOption, it implements Generator.
type GolangOptions []GolangOption

// Golang generates tests for the Go functions in seq, combining the target function's
// source, the named types it operates on, and any existing tests that
// already exercise it, into a single prompt for the model. generated tests are
// only kept if they compile and pass.
func Golang(seq iterx.Seq[Fn]) GolangOptions {
	pkgs := &pkgcache{loaded: map[string]*gopkg{}}
	callers := &callcache{built: map[string]*callindex{}}
	return GolangOptions{func(o *golangOption) {
		o.seq = seq
		o.pkgs = pkgs
		o.callers = callers
	}}
}

// Style sets an example test the generated tests should follow.
func (t GolangOptions) Style(v string) GolangOptions {
	return append(t, func(o *golangOption) {
		o.style = v
	})
}

// Filename sets the pattern for the name of the file generated tests are written to,
// next to the function's source. the file name must end in _test.go. in addition to the
// git patterns supported by eggit.StringReplace, the following are replaced:
//
//	%fn.file% -> the name of the file declaring the function, without its extension.
//	%fn.name% -> the lower cased name of the function, methods are Type_method.
//
// defaults to DefaultGolangFilename.
func (t GolangOptions) Filename(pattern string) GolangOptions {
	return append(t, func(o *golangOption) {
		o.filename = pattern
	})
}

// golangFilename resolves the file name pattern for fn.
func golangFilename(pattern string, fn Fn) (string, error) {
	name := strings.NewReplacer(
		"%fn.file%", strings.TrimSuffix(filepath.Base(fn.Path), filepath.Ext(fn.Path)),
		"%fn.name%", strings.ToLower(strings.ReplaceAll(fn.Name, ".", "_")),
	).Replace(pattern)
	name = eggit.StringReplace(name)

	if name != filepath.Base(name) {
		return "", fmt.Errorf("file name must not contain a path: %s", name)
	}

	if !strings.HasSuffix(name, "_test.go") {
		return "", fmt.Errorf("file name must end in _test.go: %s", name)
	}

	return name, nil
}

func (t GolangOptions) resolve() (o golangOption) {
	o.filename = DefaultGolangFilename
	for _, opt := range t {
		opt(&o)
	}

	return o
}

func (t GolangOptions) Seq() iterx.Seq[Fn] {
	return t.resolve().seq
}

var _ Ruler = GolangOptions(nil)

// Rules are the default rules followed by the given rules, rules already among the defaults are not repeated.
func (t GolangOptions) Rules(ensure []string) []string {
	rules := slices.Clone(golangDefaultRules)
	for _, rule := range ensure {
		if !slices.Contains(rules, rule) {
			rules = append(rules, rule)
		}
	}

	return rules
}

func (t GolangOptions) Prompt(c PromptContext) (string, error) {
	o := t.resolve()

	pkg, err := o.pkgs.load(filepath.Dir(c.Fn.Path))
	if err != nil {
		return "", err
	}

	decl := findFuncDecl(pkg, c.Fn.Name)
	if decl == nil {
		return "", fmt.Errorf("unable to locate function %s in %s", c.Fn.Name, c.Fn.Path)
	}

	codeblock, err := renderNode(pkg.fset, decl)
	if err != nil {
		return "", errorsx.Wrap(err, "unable to render function")
	}

	c.Ensure = t.Rules(c.Ensure)

	dest, existing, err := resolveTestFile(o, filepath.Dir(c.Fn.Path), c.Fn)
	if err != nil {
		return "", err
	}

	usage, err := collectUsageWithCallers(o.callers, pkg, c.Fn, decl.Name.Name)
	if err != nil {
		return "", err
	}

	testPackage, importpath, external := testPackageFor(filepath.Dir(c.Fn.Path), pkg, decl, existing)

	apis, err := collectPackages(filepath.Dir(c.Fn.Path), o.packages)
	if err != nil {
		return "", err
	}

	var buf strings.Builder
	if err := golangPromptTemplate.Execute(&buf, golangPrompt{
		PromptContext: c,
		Style:         o.style,
		Usage:         usage,
		Types:         strings.Join(nonEmpty(collectTypes(pkg, decl), apis), "\n\n"),
		Package:       pkg.name,
		TestPackage:   testPackage,
		ImportPath:    importpath,
		External:      external,
		Imports:       collectImports(pkg, decl),
		Codeblock:     codeblock,
		Existing:      string(existing),
		ExistingFile:  filepath.Base(dest),
	}); err != nil {
		return "", errorsx.Wrap(err, "unable to render prompt")
	}

	return buf.String(), nil
}

// Verify keeps the generated test next to the function only if it compiles and passes.
// the test is run in place of any existing test file by overlaying it, so the existing file is only
// replaced once the generated test passes.
func (t GolangOptions) Verify(ctx context.Context, fn Fn, artifact string) error {
	o := t.resolve()
	dir := filepath.Dir(fn.Path)

	pkg, err := o.pkgs.load(dir)
	if err != nil {
		return err
	}

	decl := findFuncDecl(pkg, fn.Name)
	if decl == nil {
		return fmt.Errorf("unable to locate function %s in %s", fn.Name, fn.Path)
	}

	dest, existing, err := resolveTestFile(o, dir, fn)
	if err != nil {
		return err
	}

	testPackage, _, _ := testPackageFor(dir, pkg, decl, existing)
	src, tests, err := extractTest(artifact, testPackage)
	if err != nil {
		return err
	}

	tests = addedTests(existing, testPackage, tests)

	tmp, err := writeTemp(dir, ".autogentest.*", src)
	if err != nil {
		return err
	}
	defer os.Remove(tmp)

	overlay, err := writeOverlay(dir, dest, tmp)
	if err != nil {
		return err
	}
	defer os.Remove(overlay)

	cmd := eggolang.Runtime().Directory(dir).Newf("go test -count=1 -cover -overlay '%s' -run '^(%s)$' .", overlay, strings.Join(tests, "|"))
	log.Printf("autogentest %s: verifying dest=%s tmp=%s overlay=%s tests=%v\n", fn.Name, dest, tmp, overlay, tests)
	if err := shell.Run(ctx, cmd.Debug()); err != nil {
		return err
	}

	return os.Rename(tmp, dest)
}

// writeOverlay writes a go build overlay presenting the file at src as the one at dest.
func writeOverlay(dir string, dest string, src string) (string, error) {
	absdest, err := filepath.Abs(dest)
	if err != nil {
		return "", err
	}

	abssrc, err := filepath.Abs(src)
	if err != nil {
		return "", err
	}

	encoded, err := json.Marshal(struct {
		Replace map[string]string
	}{Replace: map[string]string{absdest: abssrc}})
	if err != nil {
		return "", err
	}

	return writeTemp(dir, ".autogentest.overlay.*.json", encoded)
}

// pkgcache loads each directory's package once.
type pkgcache struct {
	loaded map[string]*gopkg
}

func (t *pkgcache) load(dir string) (pkg *gopkg, err error) {
	if pkg, ok := t.loaded[dir]; ok {
		return pkg, nil
	}

	if pkg, err = loadPackage(dir); err != nil {
		return nil, err
	}

	t.loaded[dir] = pkg
	return pkg, nil
}

// gopkg is the syntax of a single directory's go files, test files included.
// it's built with go/parser alone because go/packages shells out to the go
// command, which isn't possible from within the wasi runtime.
type gopkg struct {
	name  string // package name of the non test files.
	fset  *token.FileSet
	files []*ast.File
}

func loadPackage(dir string) (*gopkg, error) {
	entries, err := os.ReadDir(dir)
	if err != nil {
		return nil, errorsx.Wrapf(err, "unable to read package: %s", dir)
	}

	p := &gopkg{fset: token.NewFileSet()}
	for _, e := range entries {
		if e.IsDir() || filepath.Ext(e.Name()) != ".go" {
			continue
		}

		f, err := parser.ParseFile(p.fset, filepath.Join(dir, e.Name()), nil, parser.SkipObjectResolution)
		if err != nil {
			return nil, errorsx.Wrapf(err, "unable to parse: %s", filepath.Join(dir, e.Name()))
		}

		if p.name == "" && !strings.HasSuffix(e.Name(), "_test.go") {
			p.name = f.Name.Name
		}

		p.files = append(p.files, f)
	}

	if p.name == "" {
		return nil, fmt.Errorf("no go source files found: %s", dir)
	}

	return p, nil
}

// extractTest pulls the test file out of a model response, forces it into the
// given package, and formats it. it returns the names of the tests within.
func extractTest(response string, pkgname string) ([]byte, []string, error) {
	fset := token.NewFileSet()
	f, err := parser.ParseFile(fset, "", response, parser.ParseComments|parser.SkipObjectResolution)
	if err != nil {
		return nil, nil, errorsx.Wrap(err, "invalid go source")
	}

	f.Name.Name = pkgname

	var tests []string
	for _, d := range f.Decls {
		if fd, ok := d.(*ast.FuncDecl); ok && fd.Recv == nil && strings.HasPrefix(fd.Name.Name, "Test") {
			tests = append(tests, fd.Name.Name)
		}
	}

	if len(tests) == 0 {
		return nil, nil, fmt.Errorf("no tests found")
	}

	var buf bytes.Buffer
	if err := format.Node(&buf, fset, f); err != nil {
		return nil, nil, errorsx.Wrap(err, "unable to format")
	}

	return buf.Bytes(), tests, nil
}

// findFuncDecl locates the top level function declaration named name across
// the package's files. methods are named Type.Method.
func findFuncDecl(pkg *gopkg, name string) *ast.FuncDecl {
	for _, f := range pkg.files {
		for _, d := range f.Decls {
			if fd, ok := d.(*ast.FuncDecl); ok && golangcov.FuncName(fd) == name {
				return fd
			}
		}
	}

	return nil
}

// collectImports renders the import declarations of the file containing decl.
func collectImports(pkg *gopkg, decl *ast.FuncDecl) string {
	for _, f := range pkg.files {
		if decl.Pos() < f.Pos() || decl.End() > f.End() {
			continue
		}

		var imports []string
		for _, d := range f.Decls {
			if gd, ok := d.(*ast.GenDecl); ok && gd.Tok == token.IMPORT {
				if rendered, err := renderNode(pkg.fset, gd); err == nil {
					imports = append(imports, rendered)
				}
			}
		}

		return strings.Join(imports, "\n")
	}

	return ""
}

// resolveTestFile finds the test file the generated tests are written to and its current contents, if any.
// the test file next to the function's source (file.go -> file_test.go) is updated when it exists, otherwise
// the configured file name is used.
func resolveTestFile(o golangOption, dir string, fn Fn) (dest string, existing []byte, err error) {
	sibling := filepath.Join(dir, strings.TrimSuffix(filepath.Base(fn.Path), filepath.Ext(fn.Path))+"_test.go")
	if prev, err := os.ReadFile(sibling); err == nil {
		return sibling, prev, nil
	} else if !errors.Is(err, fs.ErrNotExist) {
		return "", nil, errorsx.Wrap(err, "unable to read existing tests")
	}

	name, err := golangFilename(o.filename, fn)
	if err != nil {
		return "", nil, err
	}

	dest = filepath.Join(dir, name)
	if prev, err := os.ReadFile(dest); err == nil {
		return dest, prev, nil
	} else if !errors.Is(err, fs.ErrNotExist) {
		return "", nil, errorsx.Wrap(err, "unable to read existing tests")
	}

	return dest, nil, nil
}

// testPackageFor is testPackageOf, except an existing test file keeps the package it declares since
// replacing it must not move its tests between the package and the external test package.
func testPackageFor(dir string, pkg *gopkg, decl *ast.FuncDecl, existing []byte) (testpackage string, importpath string, external bool) {
	testpackage, importpath, external = testPackageOf(dir, pkg, decl)

	f, err := parser.ParseFile(token.NewFileSet(), "", existing, parser.PackageClauseOnly)
	if err != nil || f.Name == nil {
		return testpackage, importpath, external
	}

	testpackage = f.Name.Name
	if external = strings.HasSuffix(testpackage, "_test"); external {
		importpath = importPathOf(dir)
	} else {
		importpath = ""
	}

	return testpackage, importpath, external
}

// importPathOf is the import path of the package in dir, empty if it isn't within a module.
func importPathOf(dir string) string {
	abs, err := filepath.Abs(dir)
	if err != nil {
		return ""
	}

	root, err := findModuleRoot(abs)
	if err != nil {
		return ""
	}

	raw, err := os.ReadFile(filepath.Join(root, "go.mod"))
	if err != nil {
		return ""
	}

	rel, err := filepath.Rel(root, abs)
	if modpath := modfile.ModulePath(raw); modpath == "" || err != nil {
		return ""
	} else {
		return path.Join(modpath, filepath.ToSlash(rel))
	}
}

// addedTests are the tests not already in the existing test file. tests the file already had may need
// things the workload doesn't have, e.g.) services, so only the added ones are run, unless none were added.
func addedTests(existing []byte, pkgname string, tests []string) []string {
	_, before, err := extractTest(string(existing), pkgname)
	if err != nil {
		return tests
	}

	added := slices.DeleteFunc(slices.Clone(tests), func(name string) bool { return slices.Contains(before, name) })
	if len(added) == 0 {
		return tests
	}

	return added
}

// testPackageOf resolves the package the generated test must declare. public apis are tested from the
// external package (name_test) like any other caller, anything else is tested from within the package.
// main packages can't be imported, and packages outside a module have no import path, so those are tested from within.
func testPackageOf(dir string, pkg *gopkg, decl *ast.FuncDecl) (testpackage string, importpath string, external bool) {
	if pkg.name == "main" || !isPublicAPI(decl) {
		return pkg.name, "", false
	}

	abs, err := filepath.Abs(dir)
	if err != nil {
		return pkg.name, "", false
	}

	root, err := findModuleRoot(abs)
	if err != nil {
		return pkg.name, "", false
	}

	raw, err := os.ReadFile(filepath.Join(root, "go.mod"))
	if err != nil {
		return pkg.name, "", false
	}

	modpath := modfile.ModulePath(raw)
	rel, err := filepath.Rel(root, abs)
	if modpath == "" || err != nil {
		return pkg.name, "", false
	}

	return pkg.name + "_test", path.Join(modpath, filepath.ToSlash(rel)), true
}

// isPublicAPI reports whether the function, or the method and the type it is declared on, is exported.
func isPublicAPI(decl *ast.FuncDecl) bool {
	if !decl.Name.IsExported() {
		return false
	}

	if decl.Recv == nil || len(decl.Recv.List) == 0 {
		return true
	}

	return ast.IsExported(golangcov.ReceiverName(decl.Recv.List[0].Type))
}

func nonEmpty(values ...string) []string {
	return slices.DeleteFunc(values, func(s string) bool { return s == "" })
}

func renderNode(fset *token.FileSet, node ast.Node) (string, error) {
	var buf bytes.Buffer
	if err := format.Node(&buf, fset, node); err != nil {
		return "", err
	}

	return buf.String(), nil
}

// collectTypes walks decl looking for references to named types declared
// within pkg, and renders each of their declarations so the model can see
// the shapes the function actually operates on.
func collectTypes(pkg *gopkg, decl *ast.FuncDecl) string {
	seen := map[string]bool{}

	ast.Inspect(decl, func(n ast.Node) bool {
		if ident, ok := n.(*ast.Ident); ok {
			seen[ident.Name] = true
		}

		return true
	})

	names := make([]string, 0, len(seen))
	for name := range seen {
		names = append(names, name)
	}
	sort.Strings(names)

	rendered := make([]string, 0, len(names))
	for _, name := range names {
		spec := findTypeSpec(pkg, name)
		if spec == nil {
			continue
		}

		// render as its own "type X ..." declaration regardless of whether
		// it was originally declared inside a grouped type (...) block.
		gd := &ast.GenDecl{Tok: token.TYPE, Specs: []ast.Spec{spec}}
		if s, err := renderNode(pkg.fset, gd); err == nil {
			rendered = append(rendered, s)
		}
	}

	return strings.Join(rendered, "\n\n")
}

// findTypeSpec locates a type declared by the package's non test files.
func findTypeSpec(pkg *gopkg, name string) *ast.TypeSpec {
	for _, f := range pkg.files {
		if strings.HasSuffix(pkg.fset.Position(f.Package).Filename, "_test.go") {
			continue
		}

		for _, d := range f.Decls {
			gd, ok := d.(*ast.GenDecl)
			if !ok {
				continue
			}

			for _, spec := range gd.Specs {
				if ts, ok := spec.(*ast.TypeSpec); ok && ts.Name.Name == name {
					return ts
				}
			}
		}
	}

	return nil
}

const maxUsageExamples = 3

// collectUsage finds existing Test/Example/Fuzz functions across pkg that
// already call a function named name, rendering up to maxUsageExamples of
// them whole as real usage examples.
func collectUsage(pkg *gopkg, name string) string {
	examples := usageExamples(pkg, name)
	if len(examples) == 0 {
		return "no existing usage of this function was found."
	}

	return strings.Join(examples, "\n\n")
}

// collectUsageWithCallers extends the tests calling the function with the statements calling it from
// the rest of its module, so there are examples even when it isn't tested.
func collectUsageWithCallers(callers *callcache, pkg *gopkg, fn Fn, name string) (string, error) {
	examples := usageExamples(pkg, name)

	calls, err := callers.callers(filepath.Dir(fn.Path), fn.Name)
	if err != nil {
		return "", err
	}

	if len(calls) > 0 {
		examples = append(examples, "call sites within the module:\n\n"+strings.Join(calls, "\n\n"))
	}

	if len(examples) == 0 {
		return "no existing usage of this function was found.", nil
	}

	return strings.Join(examples, "\n\n"), nil
}

func usageExamples(pkg *gopkg, name string) []string {
	var examples []string

	for _, f := range pkg.files {
		for _, d := range f.Decls {
			fd, ok := d.(*ast.FuncDecl)
			if !ok || fd.Recv != nil || !isTestFuncName(fd.Name.Name) || !callsFunction(fd, name) {
				continue
			}

			if rendered, err := renderNode(pkg.fset, fd); err == nil {
				examples = append(examples, rendered)
			}

			if len(examples) >= maxUsageExamples {
				return examples
			}
		}
	}

	return examples
}

func isTestFuncName(name string) bool {
	return strings.HasPrefix(name, "Test") || strings.HasPrefix(name, "Example") || strings.HasPrefix(name, "Fuzz")
}

func callsFunction(fd *ast.FuncDecl, name string) bool {
	found := false

	ast.Inspect(fd, func(n ast.Node) bool {
		call, ok := n.(*ast.CallExpr)
		if !ok {
			return true
		}

		switch fn := call.Fun.(type) {
		case *ast.Ident:
			found = found || fn.Name == name
		case *ast.SelectorExpr:
			found = found || fn.Sel.Name == name
		}

		return true
	})

	return found
}
