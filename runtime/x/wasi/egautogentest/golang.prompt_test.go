package egautogentest

import (
	"os"
	"path/filepath"
	"strings"
	"testing"

	"github.com/stretchr/testify/require"
)

func TestGolangPrompt(t *testing.T) {
	fn := Fn{Path: ".fixtures/example.1/sample.go", Name: "Greet"}

	t.Run("includes the rules", func(t *testing.T) {
		prompt, err := Golang(From(fn)).Prompt(PromptContext{Fn: fn, Ensure: []string{"no helper functions are added", "no global variables"}})
		require.NoError(t, err)
		require.Contains(t, prompt, "- no helper functions are added\n- no global variables\n\n")
		require.NotContains(t, prompt, "{{")
	})

	t.Run("adds given rules to the default rules", func(t *testing.T) {
		prompt, err := Golang(From(fn)).Prompt(PromptContext{Fn: fn, Ensure: []string{"no helper functions are added"}})
		require.NoError(t, err)
		require.Contains(t, prompt, "- no helper functions are added\n")
		for _, rule := range golangDefaultRules {
			require.Contains(t, prompt, "- "+rule+"\n")
		}
	})

	t.Run("does not repeat a given rule that is a default rule", func(t *testing.T) {
		prompt, err := Golang(From(fn)).Prompt(PromptContext{Fn: fn, Ensure: []string{golangDefaultRules[1]}})
		require.NoError(t, err)
		require.Equal(t, 1, strings.Count(prompt, "- "+golangDefaultRules[1]+"\n"))
	})

	t.Run("requires the generated file comment", func(t *testing.T) {
		prompt, err := Golang(From(fn)).Prompt(PromptContext{Fn: fn})
		require.NoError(t, err)
		require.Contains(t, prompt, "// DO NOT EDIT: This file was auto generated by egautotest.")
		require.Contains(t, prompt, "other than that first line comment you must not include *any* comments")
		require.NotContains(t, prompt, "- you must not include *any* comments")
	})

	t.Run("rules are the default rules followed by the given rules", func(t *testing.T) {
		rules := Golang(From(fn)).Rules([]string{"mine", golangDefaultRules[0]})
		require.Equal(t, append(append([]string(nil), golangDefaultRules...), "mine"), rules)
	})

	t.Run("uses the default rules without rules", func(t *testing.T) {
		prompt, err := Golang(From(fn)).Prompt(PromptContext{Fn: fn})
		require.NoError(t, err)
		for _, rule := range golangDefaultRules {
			require.Contains(t, prompt, "- "+rule+"\n")
		}
	})

	t.Run("includes the package and the imports of the function's file", func(t *testing.T) {
		shout := Fn{Path: ".fixtures/example.2/sample.go", Name: "Shout"}
		prompt, err := Golang(From(shout)).Prompt(PromptContext{Fn: shout})
		require.NoError(t, err)
		require.Contains(t, prompt, "exported from package sample")
		require.Contains(t, prompt, "\t\"fmt\"\n\t\"strings\"\n")
	})

	t.Run("tests public apis from the external package", func(t *testing.T) {
		shout := Fn{Path: ".fixtures/example.2/sample.go", Name: "Shout"}
		prompt, err := Golang(From(shout)).Prompt(PromptContext{Fn: shout})
		require.NoError(t, err)
		require.Contains(t, prompt, "\"package sample_test\"")
		require.Contains(t, prompt, "import the package under test as \"example.com/sample\"")
		require.Contains(t, prompt, "qualify its identifiers with \"sample.\"")
		require.NotContains(t, prompt, "EXISTING TESTS")
	})

	t.Run("tests public methods of exported types from the external package", func(t *testing.T) {
		rename := Fn{Path: ".fixtures/example.5/sample.go", Name: "Generic.Method"}
		prompt, err := Golang(From(rename)).Prompt(PromptContext{Fn: rename})
		require.NoError(t, err)
		require.Contains(t, prompt, "\"package sample_test\"")
	})

	t.Run("tests private apis from within the package", func(t *testing.T) {
		quiet := Fn{Path: ".fixtures/example.2/sample.go", Name: "quiet"}
		prompt, err := Golang(From(quiet)).Prompt(PromptContext{Fn: quiet})
		require.NoError(t, err)
		require.Contains(t, prompt, "not part of its public api")
		require.Contains(t, prompt, "\"package sample\"")
		require.NotContains(t, prompt, "sample_test")
	})

	t.Run("tests main packages from within the package", func(t *testing.T) {
		dir := t.TempDir()
		require.NoError(t, os.WriteFile(filepath.Join(dir, "go.mod"), []byte("module example.com/cmd\n\ngo 1.25\n"), 0o600))
		require.NoError(t, os.WriteFile(filepath.Join(dir, "main.go"), []byte("package main\n\nfunc Run() {}\n"), 0o600))

		run := Fn{Path: filepath.Join(dir, "main.go"), Name: "Run"}
		prompt, err := Golang(From(run)).Prompt(PromptContext{Fn: run})
		require.NoError(t, err)
		require.Contains(t, prompt, "\"package main\"")
		require.NotContains(t, prompt, "main_test")
	})

	t.Run("omits the imports without any", func(t *testing.T) {
		exported := Fn{Path: ".fixtures/example.5/sample.go", Name: "Exported"}
		prompt, err := Golang(From(exported)).Prompt(PromptContext{Fn: exported})
		require.NoError(t, err)
		require.Contains(t, prompt, "exported from package sample")
		require.NotContains(t, prompt, "the file containing it imports")
	})

	t.Run("includes the style and the function", func(t *testing.T) {
		prompt, err := Golang(From(fn)).Style("STYLE SAMPLE").Prompt(PromptContext{Fn: fn})
		require.NoError(t, err)
		require.Contains(t, prompt, "STYLE SAMPLE")
		require.Contains(t, prompt, "func Greet")
	})

	t.Run("does not interpret template syntax within the source", func(t *testing.T) {
		prompt, err := Golang(From(fn)).Style("{{.Fn.Name}} {{ bad").Prompt(PromptContext{Fn: fn})
		require.NoError(t, err)
		require.Contains(t, prompt, "{{.Fn.Name}} {{ bad")
	})

	t.Run("includes the test file next to the function so it is updated", func(t *testing.T) {
		prompt, err := Golang(From(fn)).Prompt(PromptContext{Fn: fn})
		require.NoError(t, err)
		require.Contains(t, prompt, "EXISTING TESTS")
		require.Contains(t, prompt, "the test file sample_test.go already exists")
		require.Contains(t, prompt, "func TestGreet(t *testing.T)")
		require.Contains(t, prompt, "\"package sample\"")
		require.NotContains(t, prompt, "sample_test\"")
	})

	t.Run("includes the generated test file without a test file next to the function", func(t *testing.T) {
		dir := t.TempDir()
		require.NoError(t, os.CopyFS(dir, os.DirFS(".fixtures/example.1")))
		require.NoError(t, os.Remove(filepath.Join(dir, "sample_test.go")))
		fn := Fn{Path: filepath.Join(dir, "sample.go"), Name: "Greet"}
		name, err := golangFilename(DefaultGolangFilename, fn)
		require.NoError(t, err)
		require.NoError(t, os.WriteFile(filepath.Join(dir, name), []byte("package sample\n\nfunc TestExisting() {}\n"), 0644))

		prompt, err := Golang(From(fn)).Prompt(PromptContext{Fn: fn})
		require.NoError(t, err)
		require.Contains(t, prompt, "EXISTING TESTS")
		require.Contains(t, prompt, "func TestExisting() {}")
	})

	t.Run("prefers the test file next to the function over the generated file", func(t *testing.T) {
		dir := t.TempDir()
		require.NoError(t, os.CopyFS(dir, os.DirFS(".fixtures/example.1")))
		fn := Fn{Path: filepath.Join(dir, "sample.go"), Name: "Greet"}
		name, err := golangFilename(DefaultGolangFilename, fn)
		require.NoError(t, err)
		require.NoError(t, os.WriteFile(filepath.Join(dir, name), []byte("package sample\n\nfunc TestGenerated() {}\n"), 0644))

		prompt, err := Golang(From(fn)).Prompt(PromptContext{Fn: fn})
		require.NoError(t, err)
		require.Contains(t, prompt, "func TestGreet(t *testing.T)")
		require.NotContains(t, prompt, "func TestGenerated() {}")
	})

	t.Run("keeps the package of the existing test file", func(t *testing.T) {
		dir := t.TempDir()
		require.NoError(t, os.CopyFS(dir, os.DirFS(".fixtures/example.1")))
		require.NoError(t, os.WriteFile(filepath.Join(dir, "sample_test.go"), []byte("package sample_test\n\nfunc TestExternal() {}\n"), 0644))
		fn := Fn{Path: filepath.Join(dir, "sample.go"), Name: "Greet"}

		prompt, err := Golang(From(fn)).Prompt(PromptContext{Fn: fn})
		require.NoError(t, err)
		require.Contains(t, prompt, "\"package sample_test\"")
		require.Contains(t, prompt, "import the package under test as \"example.com/sample\"")
	})

	t.Run("omits the existing tests section without a test file", func(t *testing.T) {
		exported := Fn{Path: ".fixtures/example.5/sample.go", Name: "Exported"}
		prompt, err := Golang(From(exported)).Prompt(PromptContext{Fn: exported})
		require.NoError(t, err)
		require.NotContains(t, prompt, "EXISTING TESTS")
	})

	t.Run("uses the configured file name to find the existing tests", func(t *testing.T) {
		dir := t.TempDir()
		require.NoError(t, os.CopyFS(dir, os.DirFS(".fixtures/example.1")))
		require.NoError(t, os.Remove(filepath.Join(dir, "sample_test.go")))
		fn := Fn{Path: filepath.Join(dir, "sample.go"), Name: "Greet"}
		require.NoError(t, os.WriteFile(filepath.Join(dir, "custom_test.go"), []byte("package sample\n\nfunc TestCustom() {}\n"), 0644))

		prompt, err := Golang(From(fn)).Filename("custom_test.go").Prompt(PromptContext{Fn: fn})
		require.NoError(t, err)
		require.Contains(t, prompt, "func TestCustom() {}")
	})

	t.Run("unknown function", func(t *testing.T) {
		_, err := Golang(From(fn)).Prompt(PromptContext{Fn: Fn{Path: fn.Path, Name: "Missing"}})
		require.Error(t, err)
	})
}
