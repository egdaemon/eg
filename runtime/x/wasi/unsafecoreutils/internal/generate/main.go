// generate writes the unsafecoreutils shims, one per utility exported by a coreutils reactor
// module (the uu_<name> exports, see coreutils/src/reactor.rs).
//
//	go run ./internal/generate -module path/to/coreutils.wasm -out unsafecoreutils.gen.go
package main

import (
	"bytes"
	"context"
	"flag"
	"fmt"
	"go/format"
	"log"
	"os"
	"slices"
	"strings"

	"github.com/tetratelabs/wazero"
)

func main() {
	var (
		module = flag.String("module", os.Getenv("EG_COREUTILS_WASM"), "path to the coreutils reactor module")
		out    = flag.String("out", "unsafecoreutils.gen.go", "file to write")
	)
	flag.Parse()

	if *module == "" {
		log.Fatalln("a coreutils reactor module is required: -module or EG_COREUTILS_WASM")
	}

	ctx := context.Background()
	raw, err := os.ReadFile(*module)
	if err != nil {
		log.Fatalln("unable to read module", err)
	}

	rt := wazero.NewRuntime(ctx)
	defer rt.Close(ctx)

	compiled, err := rt.CompileModule(ctx, raw)
	if err != nil {
		log.Fatalln("unable to compile module", err)
	}
	defer compiled.Close(ctx)

	var names []string
	for export := range compiled.ExportedFunctions() {
		if name, ok := strings.CutPrefix(export, "uu_"); ok && name != "alloc" && name != "free" && name != "chdir" {
			names = append(names, name)
		}
	}
	slices.Sort(names)

	var buf bytes.Buffer
	buf.WriteString("// Code generated by internal/generate from a coreutils reactor module. DO NOT EDIT.\n\n")
	buf.WriteString("package unsafecoreutils\n\nimport (\n\t\"context\"\n)\n")
	for _, name := range names {
		fn := strings.ToUpper(name[:1]) + name[1:]
		fmt.Fprintf(&buf, "\n// %s runs the coreutils %s utility.\nfunc %s(ctx context.Context, args ...string) error {\n\treturn run(ctx, %q, args...)\n}\n", fn, name, fn, name)
	}

	formatted, err := format.Source(buf.Bytes())
	if err != nil {
		log.Fatalln("unable to format generated code", err)
	}

	if err = os.WriteFile(*out, formatted, 0600); err != nil {
		log.Fatalln("unable to write", *out, err)
	}

	log.Println("generated", len(names), "utilities into", *out)
}
